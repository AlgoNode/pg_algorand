CREATE EXTENSION pg_algorand;

-- Address text <-> binary
SELECT AddressTxt2Bin('ALGONODEIBJTET5OSEAXIHDSIEG7C2DOFB2WDYLRZTXN3NXVJ3NJD26L4E') AS bin;
SELECT AddressBin2Txt(AddressTxt2Bin('ALGONODEIBJTET5OSEAXIHDSIEG7C2DOFB2WDYLRZTXN3NXVJ3NJD26L4E')) AS roundtrip;
SELECT AddressBin2Txt(decode(repeat('00', 32), 'hex')) AS zero_address;
SELECT AddressTxt2Bin('ALGONODE');
SELECT AddressTxt2Bin('0LGONODEIBJTET5OSEAXIHDSIEG7C2DOFB2WDYLRZTXN3NXVJ3NJD26L4E');
SELECT AddressBin2Txt('\x00'::bytea);

-- algoaddr type
SELECT 'ALGONODEIBJTET5OSEAXIHDSIEG7C2DOFB2WDYLRZTXN3NXVJ3NJD26L4E'::algoaddr;
SELECT 'ALGONODEIBJTET5OSEAXIHDSIEG7C2DOFB2WDYLRZTXN3NXVJ3NJD26L4E'::algoaddr::bytea
     = AddressTxt2Bin('ALGONODEIBJTET5OSEAXIHDSIEG7C2DOFB2WDYLRZTXN3NXVJ3NJD26L4E') AS same_bytes;
SELECT AddressTxt2Bin('ALGONODEIBJTET5OSEAXIHDSIEG7C2DOFB2WDYLRZTXN3NXVJ3NJD26L4E')::algoaddr AS via_cast;
SELECT 'TOOSHORT'::algoaddr;

-- NFD LSIG escrow addresses (deterministic; values pinned here)
SELECT length(GetNFDSigNameLSIG('algonode.algo', 760937186)) AS len;
SELECT AddressBin2Txt(GetNFDSigNameLSIG('algonode.algo', 760937186)) AS name_lsig;
SELECT AddressBin2Txt(GetNFDSigRevAddressLSIG('ALGONODEIBJTET5OSEAXIHDSIEG7C2DOFB2WDYLRZTXN3NXVJ3NJD26L4E', 760937186)) AS rev_lsig;
SELECT GetNFDSigRevAddressBinLSIG(AddressTxt2Bin('ALGONODEIBJTET5OSEAXIHDSIEG7C2DOFB2WDYLRZTXN3NXVJ3NJD26L4E'), 760937186)
     = GetNFDSigRevAddressLSIG('ALGONODEIBJTET5OSEAXIHDSIEG7C2DOFB2WDYLRZTXN3NXVJ3NJD26L4E', 760937186) AS bin_matches_txt;
SELECT GetNFDSigRevAddressBinLSIG('\x00'::bytea, 1);
